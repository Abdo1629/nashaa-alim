function sendJson(res, status, body) {
  res.statusCode = status;
  res.setHeader('Content-Type', 'application/json; charset=utf-8');
  res.setHeader('Cache-Control', 'no-store');
  res.end(JSON.stringify(body));
}

export default async function handler(req, res) {
  if (req.method !== 'POST') return sendJson(res, 405, { error: 'Method not allowed' });
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) return sendJson(res, 503, { error: 'المساعد يحتاج إلى إعداد مفتاح Gemini في إعدادات الاستضافة.' });

  try {
    const body = typeof req.body === 'string' ? JSON.parse(req.body) : (req.body || {});
    const message = typeof body.message === 'string' ? body.message.trim().slice(0, 1200) : '';
    if (!message) return sendJson(res, 400, { error: 'اكتب سؤالك الأول.' });

    const history = Array.isArray(body.history) ? body.history.slice(-10).map((item) => ({
      role: item?.role === 'model' ? 'model' : 'user',
      parts: [{ text: String(item?.text || '').slice(0, 1200) }],
    })).filter((item) => item.parts[0].text) : [];

    const contents = [...history, { role: 'user', parts: [{ text: message }] }];
    const upstream = await fetch('https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash-lite:generateContent', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'x-goog-api-key': apiKey },
      signal: AbortSignal.timeout(20000),
      body: JSON.stringify({
        systemInstruction: { parts: [{ text: SYSTEM_INSTRUCTION }] },
        contents,
        generationConfig: { maxOutputTokens: 650 },
      }),
    });

    if (!upstream.ok) {
      const errorBody = await upstream.text();
      console.error('Gemini API error:', upstream.status, errorBody.slice(0, 1000));
      return sendJson(res, 502, { error: `خدمة Gemini رجّعت خطأ (${upstream.status}). راجع إعداد الموديل وحالة المفتاح في Vercel.` });
    }

    const result = await upstream.json();
    const reply = result?.candidates?.[0]?.content?.parts?.map((part) => part.text || '').join('').trim();
    if (!reply) return sendJson(res, 502, { error: 'وصل رد غير مكتمل من المساعد. جرّب مرة تانية.' });

    const hasRegistrationWords = /(التقديم|تقديم|التسجيل|استمارة|فورم|سجل|اسجل|اشترك|اشتراك)/i.test(message);
    const hasGenericLinkRequest = /(رابط|لينك|ابعتلي|ابعت الرابط)/i.test(message)
      && !/(محاضرة|محاضرات|زوم|يوتيوب|تيليجرام|تسجيلات)/i.test(message);
    const registrationIntent = hasRegistrationWords || hasGenericLinkRequest;

    return sendJson(res, 200, { reply, showApplyButton: registrationIntent });
  } catch (error) {
    console.error('Chat API failed:', error);
    if (error?.name === 'TimeoutError' || error?.name === 'AbortError') {
      return sendJson(res, 504, { error: 'استجابة Gemini اتأخرت وانتهت مهلة الطلب. جرّب مرة تانية.' });
    }
    return sendJson(res, 500, { error: 'حصل خطأ غير متوقع. حاول مرة تانية.' });
  }
}
